import { ArrowDownRight, ArrowUpRight, ChevronDown, Layers3, Minus, ShieldAlert, Sparkles, Target, X, Copy } from 'lucide-react'
import type { Bias, SignalResult } from '../../strategy'
import { g5 } from '../../v1/types'
import { PRO_RISK_LABELS, STRATEGY_LABELS } from '../../v3/types'
import { formatCambodiaChartTime, formatCambodiaTime } from '../../marketSession'

const biasText: Record<Bias | 'wait', string> = {
  buy: 'Buy',
  sell: 'Sell',
  neutral: 'Neutral',
  wait: 'No signal',
}

const viewText = {
  BULLISH: 'Bullish',
  BEARISH: 'Bearish',
  RANGING: 'Sideways',
} as const

const statusText: Record<string, string> = {
  ACTIVE: 'Active',
  TP1_HIT: 'TP1 hit · slot unlocked',
  TP2_HIT: 'TP2 hit',
  TP3_HIT: 'TP3 hit',
  STOP_LOSS_HIT: 'Stop loss hit',
  CLOSED: 'Closed',
  CANCELLED: 'Cancelled',
}

function generatePineScript(result: SignalResult): string {
  const levels = result.levels
  if (!levels) return ''

  const isBuy = result.action === 'BUY'
  const entry = levels.entry.toFixed(5)
  const sl = levels.stopLoss.toFixed(5)
  const tp1 = levels.tp1.toFixed(5)
  const tp2 = levels.tp2 !== null ? levels.tp2.toFixed(5) : null
  const tp3 = levels.tp3 !== null ? levels.tp3.toFixed(5) : null
  const entryLow = levels.entryZoneLow.toFixed(5)
  const entryHigh = levels.entryZoneHigh.toFixed(5)
  const symbol = result.symbol.replace('/', '')
  const timeframe = result.timeframe
  const analysisPlan = result.strategy === 'V3' ? 'Pro' : result.strategy === 'V2' ? 'Plus' : 'Free'

  return `//@version=5
indicator("${analysisPlan} Analysis · ${result.symbol} ${result.timeframe}", overlay=true)

// ── Inputs ──
entryPrice = input.float(${entry}, "Entry Price")
slPrice    = input.float(${sl}, "Stop Loss")
tp1Price   = input.float(${tp1}, "Take Profit 1")
tp2Price   = input.float(${tp2 ?? 'na'}, "Take Profit 2")
tp3Price   = input.float(${tp3 ?? 'na'}, "Take Profit 3")
entryZoneLow  = input.float(${entryLow}, "Entry Zone Low")
entryZoneHigh = input.float(${entryHigh}, "Entry Zone High")
showLevels   = input.bool(true, "Show Levels")
showZone     = input.bool(true, "Show Entry Zone")
showLabels   = input.bool(true, "Show Labels")

// ── Colors ──
${isBuy ? `buyColor   = #42c6a5
sellColor  = #f07480
zoneColor  = #eab86a` : `buyColor   = #42c6a5
sellColor  = #f07480
zoneColor  = #eab86a`}

// ── Plot Levels ──
plot(showLevels ? entryPrice : na, "Entry", ${isBuy ? 'buyColor' : 'sellColor'}, 2, plot.style_linebr)
plot(showLevels ? slPrice    : na, "Stop Loss", #f07480, 2, plot.style_linebr)
plot(showLevels ? tp1Price   : na, "TP1", #42c6a5, 2, plot.style_linebr)
plot(not na(tp2Price) and showLevels ? tp2Price : na, "TP2", #42c6a5, 1, plot.style_linebr)
plot(not na(tp3Price) and showLevels ? tp3Price : na, "TP3", #42c6a5, 1, plot.style_linebr)

// ── Entry Zone ──
zoneTop    = math.max(entryZoneLow, entryZoneHigh)
zoneBottom = math.min(entryZoneLow, entryZoneHigh)
p1 = plot(showZone ? zoneTop    : na, "Zone Top", zoneColor, 1)
p2 = plot(showZone ? zoneBottom : na, "Zone Bottom", zoneColor, 1)
fill(p1, p2, color.new(zoneColor, 90))

// ── Labels ──
var label entryLabel = na
var label slLabel    = na
var label tp1Label   = na
var label tp2Label   = na
var label tp3Label   = na

if barstate.islast and showLabels
    if na(entryLabel)
        entryLabel := label.new(bar_index, entryPrice, "ENTRY " + str.tostring(entryPrice, "#.#####"), color=${isBuy ? 'buyColor' : 'sellColor'}, style=label.style_label_down, textcolor=color.white, size=size.small)
        slLabel    := label.new(bar_index, slPrice, "SL " + str.tostring(slPrice, "#.#####"), color=#f07480, style=label.style_label_down, textcolor=color.white, size=size.small)
        tp1Label   := label.new(bar_index, tp1Price, "TP1 " + str.tostring(tp1Price, "#.#####"), color=#42c6a5, style=label.style_label_up, textcolor=color.white, size=size.small)
        if not na(tp2Price)
            tp2Label := label.new(bar_index, tp2Price, "TP2 " + str.tostring(tp2Price, "#.#####"), color=#42c6a5, style=label.style_label_up, textcolor=color.white, size=size.small)
        if not na(tp3Price)
            tp3Label := label.new(bar_index, tp3Price, "TP3 " + str.tostring(tp3Price, "#.#####"), color=#42c6a5, style=label.style_label_up, textcolor=color.white, size=size.small)

// ── Alert ──
alertcondition(ta.cross(close, entryPrice), "Entry Alert", "Price reached entry zone for ${result.symbol} ${result.timeframe}")

// ── Info ──
plotchar(barstate.islast, "Signal", "${isBuy ? 'BUY' : 'SELL'} ${result.symbol} ${result.timeframe} · Score ${result.score.total.toFixed(0)}/100", location.top)

/*
  Generated by SOVANNAPHUMTRADE ${analysisPlan} Analysis
  Symbol: ${result.symbol}
  Timeframe: ${result.timeframe}
  Action: ${result.action}
  Score: ${result.score.total.toFixed(0)}/100 (${result.score.band})
  Playbook: ${result.strategyName ?? 'Auto'}
  Entry Zone: ${entryLow} – ${entryHigh}
  Entry: ${entry}
  Stop Loss: ${sl}
  TP1: ${tp1}${tp2 ? ` · TP2: ${tp2}` : ''}${tp3 ? ` · TP3: ${tp3}` : ''}
  R:R TP1: ${levels.rrTp1.toFixed(2)}
  Bar Time: ${result.barTime ? new Date(result.barTime).toISOString() : 'N/A'}
  Provider: ${result.provider}
  ─────────────────────────────────────────
  Copy this script into TradingView Pine Editor → Add to Chart
  Works on any timeframe, but levels are from the ${result.timeframe} analysis.
*/
`
}

const v2StatusText: Record<string, string> = {
  ACTIVE: 'Active',
  TP1_HIT: 'TP1 hit · 50% closed, stop at breakeven',
  TP2_HIT: 'TP2 hit',
  TP3_HIT: 'TP3 hit · closed',
  STOP_LOSS_HIT: 'Stop loss hit',
  CLOSED: 'Closed',
  CANCELLED: 'Cancelled',
}

const v3StatusText: Record<string, string> = {
  ACTIVE: 'Active · one signal per setup',
  TP1_HIT: 'TP1 hit · 50% closed, slot unlocked',
  TP2_HIT: 'TP2 hit · runner at breakeven',
  TP3_HIT: 'TP3 hit · closed',
  STOP_LOSS_HIT: 'Stop loss hit',
  CLOSED: 'Closed',
  CANCELLED: 'Cancelled',
}

function BiasIcon({ bias, size = 14 }: { bias: Bias | 'wait'; size?: number }) {
  if (bias === 'buy') return <ArrowUpRight size={size} />
  if (bias === 'sell') return <ArrowDownRight size={size} />
  return <Minus size={size} />
}

function LevelCard({ label, value, note }: { label: string; value: string; note?: string }) {
  return (
    <div className="signal-level">
      <span>{label}</span>
      <strong>{value}</strong>
      {note && <small>{note}</small>}
    </div>
  )
}

function Limits({ result }: { result: SignalResult }) {
  const analyses = result.limits.analyses < 0 ? 'Unlimited analyses' : `${result.limits.analyses} analyses left today`
  const signals = result.limits.signals < 0 ? 'unlimited signals' : `${result.limits.signals} signals left today`
  if (result.strategy === 'V2' || result.strategy === 'V3') {
    const best = result.limits.bestSetups < 0 ? 'best setups unlimited' : `${result.limits.bestSetups} best-setup slots left`
    const scans = result.limits.scans < 0 ? 'scans unlimited' : `${result.limits.scans} scanner analyses left`
    return <span className="signal-limit">{analyses} · {signals} · {best} · {scans}</span>
  }
  return <span className="signal-limit">{analyses} · {signals}</span>
}

function SetupRow({ setup }: { setup: SignalResult['openSignals'][number] }) {
  return (
    <li className="signal-setup-row">
      <strong>{setup.symbol} <span>· {setup.timeframe}</span></strong>
      <em className={`is-${setup.direction === 'BUY' ? 'buy' : 'sell'}`}>{setup.direction}</em>
      <small>{setup.score.toFixed(0)}/100 · Entry {g5(setup.entry)} · SL {g5(setup.stopLoss)} · TP1 {g5(setup.tp1)}</small>
    </li>
  )
}

export default function SignalPanel({ result, onClose }: { result: SignalResult; onClose: () => void }) {
  const time = formatCambodiaTime(new Date(result.generatedAt), false)
  const bar = result.barTime
    ? formatCambodiaChartTime(result.barTime / 1000)
    : null
  const levels = result.levels
  const v2 = result.strategy === 'V2'
  const v3 = result.strategy === 'V3'
  const generated = result.action === 'BUY' || result.action === 'SELL'
  const minimumScore = v3 ? 70 : 60
  const scoreThresholdPassed = result.score.total > minimumScore
  const statusLabels = v3 ? v3StatusText : v2 ? v2StatusText : statusText
  const keyLevels = (v2 || v3) && 'keyLevels' in result.structure && Array.isArray(result.structure.keyLevels)
    ? result.structure.keyLevels
    : []

  return (
    <section className={`signal-panel is-${result.bias}`}>
      <header className="signal-head">
        <div className="signal-head-main">
          <span className={`signal-kicker ${v3 ? 'is-v3' : v2 ? 'is-v2' : ''}`}><Sparkles size={12} /> {v3 ? 'PRO ANALYSIS' : v2 ? 'PLUS ANALYSIS' : 'FREE ANALYSIS'}</span>
          <h3>
            {result.symbol} <span>· {result.timeframe}</span>
            <em className={`signal-preview is-${result.action.toLowerCase()}`}>{result.action.replace('_', ' ')}</em>
          </h3>
        </div>
        <div className="signal-head-side">
          <span className="signal-time">
            Analyzed {time} ICT{bar ? ` · bar ${bar} ICT` : ''}
          </span>
          {result.levels && (
            <button
              className="icon-button"
              aria-label="Copy Pine Script for TradingView"
              onClick={() => {
                const script = generatePineScript(result)
                navigator.clipboard.writeText(script)
              }}
            >
              <Copy size={15} />
            </button>
          )}
          <button className="icon-button" aria-label="Close signal result" onClick={onClose}><X size={15} /></button>
        </div>
      </header>

      <div className="signal-verdict">
        <span className={`signal-verdict-badge is-${result.bias}`}>
          <BiasIcon bias={result.bias} size={16} />
          {biasText[result.bias]}
        </span>
        <div className="signal-verdict-copy">
          <strong>{result.headline}</strong>
          <p>{result.summary}</p>
          <div className="signal-verdict-meta">
            <span>View: <b>{viewText[result.view]}</b></span>
            <span>Score: <b>{result.score.total.toFixed(0)}/100</b></span>
            <span>Band: <b>{result.score.band}</b></span>
            {v3 && result.strategyName && <span>Playbook: <b>{STRATEGY_LABELS[result.strategyName]}</b></span>}
            {v3 && result.riskProfile && <span>Profile: <b>{PRO_RISK_LABELS[result.riskProfile]}</b></span>}
            {v3 && <span>Selection: <b>{result.requestedStrategy ? 'Manual' : 'Auto'}</b></span>}
            {v3 && result.regime && <span>Regime: <b>{result.regime.label}</b></span>}
            {result.status && <span>Trade state: <b>{statusLabels[result.status] ?? result.status}</b></span>}
          </div>
        </div>
        <div className={`signal-confidence ${generated ? 'is-validated' : 'is-blocked'}`}>
          <span>{generated ? 'Validated score' : 'Raw setup score'}</span>
          <strong>{Math.round(result.score.total)}/100</strong>
          <div className="signal-meter"><i style={{ width: `${Math.min(100, result.score.total)}%` }} /></div>
          <small>{generated ? 'All required gates passed' : scoreThresholdPassed ? 'Score passed · mandatory gate failed' : `Must be above ${minimumScore}/100`}</small>
        </div>
      </div>

      {!generated && (
        <div className="signal-gate-explanation">
          <ShieldAlert size={16} />
          <div>
            <strong>{scoreThresholdPassed ? 'Score threshold passed, but validation did not' : `Score must be higher than ${minimumScore}/100`}</strong>
            <p>{scoreThresholdPassed
              ? 'The score measures aligned evidence, not probability. BUY/SELL still requires every structure, confirmation, risk, cooldown and account gate to pass.'
              : 'The setup needs a higher weighted score plus every mandatory structure, confirmation, risk, cooldown and account rule.'}</p>
          </div>
        </div>
      )}

      {result.existingActive && (
        <div className="signal-existing">
          <ShieldAlert size={16} />
          <div>
            <strong>Active {result.existingActive.direction} · {result.existingActive.symbol} {result.existingActive.timeframe}</strong>
            <p>
              {statusLabels[result.existingActive.status] ?? result.existingActive.status} · Entry {g5(result.existingActive.levels.entry)} ·
              {' '}SL {g5(result.existingActive.currentStopLoss ?? result.existingActive.levels.stopLoss)} ·
              {' '}TP1 {g5(result.existingActive.levels.tp1)}
            </p>
          </div>
        </div>
      )}

      {(v2 || v3) && (result.openSignals.length > 0 || result.bestSetups.length > 0) && (
        <div className="signal-setups">
          {result.openSignals.length > 0 && (
            <div className="signal-setups-col">
              <span className="signal-setups-head"><Target size={12} /> Open setups ({result.openSignals.length})</span>
              <ul>{result.openSignals.slice(0, 4).map(setup => <SetupRow key={setup.signalId} setup={setup} />)}</ul>
            </div>
          )}
          {result.bestSetups.length > 0 && (
            <div className="signal-setups-col">
              <span className="signal-setups-head"><Sparkles size={12} /> {v3 ? 'Best setups · 365-day history' : 'Best setups today'}</span>
              <ul>{result.bestSetups.slice(0, 4).map(setup => <SetupRow key={`best-${setup.signalId}`} setup={setup} />)}</ul>
            </div>
          )}
        </div>
      )}

      {keyLevels.length > 0 && (
        <div className="signal-key-levels-block">
          <div className="signal-levels-head">
            <span><Layers3 size={13} /> Confirmed key levels</span>
            <small>Built only from closed, right-confirmed swing points</small>
          </div>
          <div className="signal-key-levels">
            {keyLevels.map((level, index) => (
              <div className={`signal-key-level is-${level.kind.toLowerCase()}`} key={`${level.kind}-${level.price}-${index}`}>
                <span>{level.kind === 'SUPPORT' ? 'Support' : 'Resistance'}</span>
                <strong>{g5(level.price)}</strong>
                <small>{level.strength.toLowerCase()} · {level.touches} touch{level.touches === 1 ? '' : 'es'}</small>
                <i style={{ width: `${level.score}%` }} />
              </div>
            ))}
          </div>
        </div>
      )}

      {levels && (
        <div className="signal-levels-block">
          <div className="signal-levels-head">
            <span><Target size={13} /> Trade levels</span>
            <small>Frozen from the closed candle · {result.provider}{v3 && result.suggestedRiskPercent ? ` · Suggested account risk ${result.suggestedRiskPercent}%` : ''}</small>
          </div>
          <div className="signal-levels">
            <LevelCard label="Entry zone" value={`${g5(levels.entryZoneLow)} – ${g5(levels.entryZoneHigh)}`} note={`Entry ${g5(levels.entry)}`} />
            <LevelCard label="Stop loss" value={g5(levels.stopLoss)} note={`Risk ${g5(levels.risk)}`} />
            <LevelCard label="TP1" value={g5(levels.tp1)} note={`${levels.rrTp1.toFixed(2)}R · ${Math.round(((v2 || v3) ? levels.tp1CloseFraction ?? 0.5 : levels.allocations[0]) * 100)}%${v2 || v3 ? ' close' : ''}`} />
            {levels.tp2 !== null && <LevelCard label="TP2" value={g5(levels.tp2)} note={`${levels.rrTp2!.toFixed(2)}R · ${Math.round((levels.allocations[1] ?? 0) * 100)}%`} />}
            {levels.tp3 !== null && <LevelCard label="TP3 (optional)" value={g5(levels.tp3)} note={`${levels.rrTp3!.toFixed(2)}R · ${Math.round((levels.allocations[2] ?? 0) * 100)}%`} />}
            <LevelCard label="Breakeven after TP1" value={g5(levels.breakevenStop)} note="Stop moves here after TP1" />
          </div>
          <p className="signal-level-source">
            Based on: {levels.references.join(' · ')}
          </p>
        </div>
      )}

      <div className="signal-groups">
        {result.groups.map((group, index) => (
          <details className={`signal-group is-${group.bias}`} key={group.id} open={index === 0}>
            <summary className="signal-group-head">
              <strong>{group.label}</strong>
              <span className="signal-group-summary">
                <span className="signal-group-score-inline">{group.score}/{group.max}</span>
                <span className={`signal-chip is-${group.bias}`}>
                  <BiasIcon bias={group.bias} size={11} />
                  {biasText[group.bias]}
                </span>
                <ChevronDown size={13} className="signal-group-chevron" />
              </span>
            </summary>
            <div className="signal-group-score">
              <div className="signal-meter"><i style={{ width: `${Math.min(100, (group.score / group.max) * 100)}%` }} /></div>
              <small>{group.score}/{group.max}</small>
            </div>
            <ul className="signal-reasons">
              {group.reasons.map(reason => (
                <li key={reason.label} className={`is-${reason.bias}`}>
                  <span className="signal-reason-dot" />
                  <div>
                    <strong>{reason.label}</strong>
                    <small>{reason.detail}</small>
                  </div>
                  <em>{biasText[reason.bias]}</em>
                </li>
              ))}
            </ul>
          </details>
        ))}
      </div>

      <div className="signal-footer">
        <div className="signal-notes">
          {result.dataNotes.map(note => <span key={note}>{note}</span>)}
        </div>
        <Limits result={result} />
      </div>

      <p className="signal-note">
        {v3
          ? 'Pro Analysis selects the best-fitting playbook on closed candles only. One active setup per market and timeframe; TP1 unlocks the slot while the runner stays protected at breakeven plus costs. This is decision support, not financial advice.'
          : v2
            ? 'Plus Analysis uses rule-based closed-candle checks. Plus allows up to 15 signals a day; TP1 closes 50% and the runner moves to breakeven after costs. This is decision support, not financial advice.'
            : 'Free Analysis uses rule-based closed-candle checks. One active setup is allowed at a time; the next setup unlocks after TP1. This is decision support, not financial advice.'}
      </p>
    </section>
  )
}
